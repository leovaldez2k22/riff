"""Feature 21 (Riff+): writes the 24 launcher icons (styles A, C, D x eight colours), their activity aliases, their
system launch-screen themes and the Kotlin table that names them. Run from the repository root:

    python -I scripts/appearance/generate_icons.py

Every shape comes from Riff's own ribbon path (app/src/main/res/drawable/ic_launcher_foreground.xml). The colours
here must match AccentPreset in app/src/plus/java/com/musicglass/personal/Appearance.kt (AppearanceTest checks).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLUS = ROOT / "app/src/plus"

RIBBONS = ("M27,49 C37,57 43,41 51,34 C61,25 71,30 78,41 C66,34 61,43 53,51 C43,61 34,60 27,49 Z "
           "M29,64 C41,73 47,59 55,52 C66,41 76,46 81,56 C68,49 64,63 56,70 C46,80 36,76 29,64 Z")
BADGE = "M72.7,25 L75.3,25 L75.3,27.7 L78,27.7 L78,30.3 L75.3,30.3 L75.3,33 L72.7,33 L72.7,30.3 L70,30.3 L70,27.7 L72.7,27.7 Z"
DARK = "#09090B"

# key: (name, icon colour, D's partner colour)
COLOURS = {
    "rose": ("Rose", "#F45B9A", "#8B6CF2"),
    "violet": ("Violet", "#8B6CF2", "#F45B9A"),
    "blue": ("Blue", "#3E8EF0", "#F2A93B"),
    "teal": ("Teal", "#22B8A8", "#F2664F"),
    "green": ("Green", "#4CC060", "#3E8EF0"),
    "amber": ("Amber", "#F2A93B", "#8B6CF2"),
    "coral": ("Coral", "#F2664F", "#22B8A8"),
    "silver": ("Silver", "#B4B9C4", "#6E7380"),
}
STYLES = ("a", "c", "d")


def vector(groups):
    body = "\n".join(groups)
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/appearance/generate_icons.py; do not edit. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            '    <group android:pivotX="54" android:pivotY="54" android:scaleX="0.9" android:scaleY="0.9">\n'
            f'{body}\n    </group>\n</vector>\n')


def path(d, colour, rotate=False):
    p = f'        <path android:fillColor="{colour}" android:pathData="{d}" />'
    return (f'        <group android:pivotX="54" android:pivotY="54" android:rotation="90">\n    {p}\n        </group>') if rotate else p


def foreground(style, colour):
    _, front, partner = COLOURS[colour]
    if style == "a":
        return vector([path(RIBBONS, front), path(BADGE, front)])
    if style == "c":
        return vector([path(RIBBONS, DARK), path(BADGE, DARK)])
    return vector([path(RIBBONS, partner, rotate=True), path(RIBBONS, front)])


def monochrome(style):
    if style == "d":
        return vector([path(RIBBONS, "#FFFFFF", rotate=True), path(RIBBONS, "#FFFFFF")])
    return vector([path(RIBBONS, "#FFFFFF"), path(BADGE, "#FFFFFF")])


def adaptive(style, colour):
    background = f"@color/launcher_tile_{colour}" if style == "c" else "@color/launcher_background"
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/appearance/generate_icons.py; do not edit. -->\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <background android:drawable="{background}" />\n'
            f'    <foreground android:drawable="@drawable/ic_launcher_fg_{style}_{colour}" />\n'
            f'    <monochrome android:drawable="@drawable/ic_launcher_mono_{"d" if style == "d" else "a"}" />\n'
            '</adaptive-icon>\n')


def alias_name(style, colour):
    return f"Launcher{style.upper()}{COLOURS[colour][0]}"


def write(path_, text):
    path_.parent.mkdir(parents=True, exist_ok=True)
    path_.write_text(text, encoding="utf-8", newline="\n")


def main():
    for style in STYLES:
        for colour in COLOURS:
            write(PLUS / f"res/drawable/ic_launcher_fg_{style}_{colour}.xml", foreground(style, colour))
            write(PLUS / f"res/mipmap-anydpi-v26/ic_launcher_{style}_{colour}.xml", adaptive(style, colour))
    for style in ("a", "d"):
        write(PLUS / f"res/drawable/ic_launcher_mono_{style}.xml", monochrome(style))

    colours = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by scripts/appearance/generate_icons.py; do not edit. -->", "<resources>"]
    colours += [f'    <color name="launcher_tile_{k}">{v[1]}</color>' for k, v in COLOURS.items()]
    write(PLUS / "res/values/appearance_colors.xml", "\n".join(colours + ["</resources>"]) + "\n")

    themes = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by scripts/appearance/generate_icons.py; do not edit.",
              "     Android's own launch screen for each icon, set with SplashScreen.setSplashScreenTheme (API 31). -->", "<resources>"]
    for style in STYLES:
        for colour in COLOURS:
            themes.append(f'    <style name="RiffSplash.{style.upper()}.{COLOURS[colour][0]}" parent="@android:style/Theme.Material.NoActionBar">')
            themes.append('        <item name="android:windowSplashScreenBackground">@color/launcher_background</item>')
            themes.append(f'        <item name="android:windowSplashScreenAnimatedIcon">@drawable/ic_launcher_fg_{style}_{colour}</item>')
            if style == "c":
                themes.append(f'        <item name="android:windowSplashScreenIconBackgroundColor">@color/launcher_tile_{colour}</item>')
            themes.append("    </style>")
    write(PLUS / "res/values/appearance_splash.xml", "\n".join(themes + ["</resources>"]) + "\n")

    aliases = []
    for style in STYLES:
        for colour in COLOURS:
            default = "true" if (style, colour) == ("a", "rose") else "false"
            aliases.append(f'        <activity-alias android:name=".{alias_name(style, colour)}" android:targetActivity=".MainActivity"\n'
                           f'            android:enabled="{default}" android:exported="true" android:label="@string/app_name"\n'
                           f'            android:icon="@mipmap/ic_launcher_{style}_{colour}" android:roundIcon="@mipmap/ic_launcher_{style}_{colour}">\n'
                           '            <intent-filter>\n                <action android:name="android.intent.action.MAIN" />\n'
                           '                <category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>\n'
                           '        </activity-alias>')
    manifest = PLUS / "AndroidManifest.xml"
    text = manifest.read_text(encoding="utf-8")
    start, end = "        <!-- appearance aliases: generated -->", "        <!-- appearance aliases: end -->"
    block = start + "\n" + "\n".join(aliases) + "\n" + end
    if start in text:
        text = text[:text.index(start)] + block + text[text.index(end) + len(end):]
    else:
        text = text.replace("    </application>", block + "\n    </application>")
    write(manifest, text)

    kt = ["package com.musicglass.personal", "", "// Generated by scripts/appearance/generate_icons.py; do not edit.", "",
          "/** Feature 21: each icon's alias, launcher picture and launch-screen theme, by style and colour key. */",
          "internal val launcherIcons: Map<String, LauncherIcon> = mapOf("]
    for style in STYLES:
        for colour in COLOURS:
            kt.append(f'    "{style}_{colour}" to LauncherIcon("com.musicglass.personal.{alias_name(style, colour)}", '
                      f'R.mipmap.ic_launcher_{style}_{colour}, R.style.RiffSplash_{style.upper()}_{COLOURS[colour][0]}),')
    kt.append(")")
    write(PLUS / "java/com/musicglass/personal/LauncherIcons.kt", "\n".join(kt) + "\n")
    print("24 icons, 24 aliases, 24 launch themes")


if __name__ == "__main__":
    main()
