// PLAN.md Task 1.5: the design tokens are generated from Android's DesignTokens.kt at build time, so they cannot
// drift. The canonical part is everything from RiffSpace up to the doc comment of RiffTheme (a MaterialTheme, which
// desktop does not use), and everything from RiffContrast to the end. It is copied verbatim; only the package line
// changes, and imports the copied part does not use are dropped. -PriffTokenSource=<file> reads another copy (tests).
val riffTokenSource = providers.gradleProperty("riffTokenSource").map { file(it) }
    .orElse(rootProject.layout.projectDirectory.file("app/src/main/java/com/musicglass/personal/DesignTokens.kt").asFile)
val riffTokenOutput = layout.buildDirectory.dir("generated/riffTokens")
val generateCanonicalTokens = tasks.register("generateCanonicalTokens") {
    val source = riffTokenSource
    val output = riffTokenOutput
    inputs.file(source)
    outputs.dir(output)
    doLast {
        val path = source.get()
        val text = path.readText(Charsets.UTF_8).replace("\r\n", "\n")
        fun marker(found: Int, what: String) = found.also { check(it >= 0) { "$path: token marker missing: $what" } }
        check(!Regex("(?m)^import android\\.").containsMatchIn(text)) { "$path imports android.*: desktop cannot use it" }
        val first = marker(text.indexOf("internal object RiffSpace"), "internal object RiffSpace")
        val theme = marker(text.indexOf(" * The one theme"), "the RiffTheme doc comment (\" * The one theme\")")
        val firstEnd = marker(text.lastIndexOf("/**", theme), "the /** before RiffTheme")
        val second = marker(text.indexOf("internal object RiffContrast"), "internal object RiffContrast")
        check(first < firstEnd && firstEnd < second) { "$path: token markers are out of order" }
        val body = text.substring(first, firstEnd).trim() + "\n\n" + text.substring(second).trim() + "\n"
        val imports = Regex("(?m)^import ([\\w.]+)$").findAll(text).map { it.groupValues[1] }
            .filter { name -> Regex("\\b${Regex.escape(name.substringAfterLast('.'))}\\b").containsMatchIn(body) }
            .joinToString("") { "import $it\n" }
        output.get().file("com/musicglass/desktop/CanonicalTokens.kt").asFile.apply {
            parentFile.mkdirs()
            writeText("// Generated by :desktop:generateCanonicalTokens from app/src/main/java/com/musicglass/personal/DesignTokens.kt.\n" +
                "// Do not edit: change Android's file.\npackage com.musicglass.desktop\n\n$imports\n$body", Charsets.UTF_8)
        }
    }
}
kotlin.sourceSets.main { kotlin.srcDir(generateCanonicalTokens) }

